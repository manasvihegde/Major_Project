def fetch_all_runs(conn):
    """
    Returns all completed experiment runs.
    """

    cur = conn.cursor()

    cur.execute("""
        SELECT id
        FROM run_logs
        WHERE status='done'
        ORDER BY id;
    """)

    runs = [row[0] for row in cur.fetchall()]

    cur.close()

    return runs


# ============================================================
# FETCH QUESTIONS
# ============================================================

def fetch_questions(conn, run_id):
    """
    Returns all questions processed in a run.
    """

    cur = conn.cursor()

    cur.execute("""
        SELECT DISTINCT question_id
        FROM model_outputs
        WHERE run_id=%s
        ORDER BY question_id;
    """, (run_id,))

    questions = [row[0] for row in cur.fetchall()]

    cur.close()

    return questions


# ============================================================
# FETCH ORIGINAL OUTPUT
# ============================================================

def fetch_original_output(conn, run_id, question_id):
    """
    Original output has perturbation_id = NULL.
    """

    cur = conn.cursor()

    cur.execute("""
        SELECT reasoning_chain
        FROM model_outputs
        WHERE run_id=%s
          AND question_id=%s
          AND perturbation_id IS NULL;
    """, (run_id, question_id))

    row = cur.fetchone()

    cur.close()

    if row is None:
        return None

    return row[0]


# ============================================================
# FETCH PERTURBED OUTPUTS
# ============================================================

def fetch_perturbed_outputs(conn, run_id, question_id):
    """
    Returns every perturbed output for a question.
    """

    cur = conn.cursor()

    cur.execute("""
        SELECT

            mo.perturbation_id,

            p.perturbation_type,

            mo.reasoning_chain

        FROM model_outputs mo

        INNER JOIN perturbations p

            ON mo.perturbation_id = p.id

        WHERE

            mo.run_id=%s

            AND

            mo.question_id=%s

        ORDER BY

            mo.perturbation_id;
    """, (run_id, question_id))

    rows = cur.fetchall()

    cur.close()

    return rows


# ============================================================
# FETCH SEMANTIC SIMILARITY
# ============================================================

def fetch_semantic_similarity(
        conn,
        run_id,
        question_id,
        perturbation_type
):
    """
    Read similarity already computed by comparative_logger.py
    """

    column_map = {

        "prefix": "score_prefix",

        "name_swap": "score_name_swap",

        "synonym": "score_synonym",

        "whitespace": "score_whitespace"

    }

    column = column_map.get(perturbation_type)

    if column is None:
        return None

    cur = conn.cursor()

    cur.execute(f"""
        SELECT {column}
        FROM stability_scores
        WHERE run_id=%s
          AND question_id=%s;
    """, (run_id, question_id))

    row = cur.fetchone()

    cur.close()

    if row is None:
        return None

    return safe_similarity(row[0])


# ============================================================
# INSERT INTO instability_categories
# ============================================================

def insert_instability(
    conn,
    run_id,
    question_id,
    perturbation_id,
    perturbation_type,
    output_ratio,
    semantic_similarity,
    category,
):

    cur = conn.cursor()

    cur.execute("""

        INSERT INTO instability_categories(

            run_id,

            question_id,

            perturbation_id,

            perturbation_type,

            output_edit_ratio,

            semantic_similarity,

            instability_category

        )

        VALUES(

            %s,%s,%s,%s,%s,%s,%s

        )

        ON CONFLICT(

            run_id,

            question_id,

            perturbation_id

        )

        DO UPDATE

        SET

            output_edit_ratio =
                EXCLUDED.output_edit_ratio,

            semantic_similarity =
                EXCLUDED.semantic_similarity,

            instability_category =
                EXCLUDED.instability_category;

    """, (

        run_id,

        question_id,

        perturbation_id,

        perturbation_type,

        output_ratio,

        semantic_similarity,

        category

    ))

    conn.commit()

    cur.close()


