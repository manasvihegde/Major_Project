import csv
import difflib
import os

import psycopg2
from dotenv import load_dotenv

# ============================================================
# Load Environment Variables
# ============================================================

load_dotenv()

# ============================================================
# Configuration
# ============================================================

CSV_FILENAME = "week2_analysis.csv"

# Thresholds
SEMANTIC_THRESHOLD = 0.85
EDIT_RATIO_THRESHOLD = 0.95

# ============================================================
# Database Connection
# ============================================================

def get_connection():
    """
    Create PostgreSQL connection.
    """

    return psycopg2.connect(
        host=os.getenv("DB_HOST", "localhost"),
        port=os.getenv("DB_PORT", "5432"),
        dbname=os.getenv("DB_NAME"),
        user=os.getenv("DB_USER"),
        password=os.getenv("DB_PASSWORD"),
    )


# ============================================================
# CSV FUNCTIONS
# ============================================================

def initialize_csv():
    """
    Create CSV file with header.
    """

    with open(
        CSV_FILENAME,
        "w",
        newline="",
        encoding="utf-8"
    ) as file:

        writer = csv.writer(file)

        writer.writerow([
            "Run ID",
            "Question ID",
            "Perturbation ID",
            "Perturbation Type",
            "Output Edit Ratio",
            "Semantic Similarity",
            "Instability Category"
        ])


def write_csv(
    run_id,
    question_id,
    perturbation_id,
    perturbation_type,
    output_ratio,
    semantic_similarity,
    category,
):

    with open(
        CSV_FILENAME,
        "a",
        newline="",
        encoding="utf-8"
    ) as file:

        writer = csv.writer(file)

        writer.writerow([
            run_id,
            question_id,
            perturbation_id,
            perturbation_type,
            round(output_ratio, 4),
            round(semantic_similarity, 4),
            category
        ])


# ============================================================
# OUTPUT EDIT RATIO
# ============================================================

def output_edit_ratio(
    original_output,
    perturbed_output,
):
    """
    Returns similarity between two generated outputs.

    1.0 = identical outputs
    0.0 = completely different outputs
    """

    return round(
        difflib.SequenceMatcher(
            None,
            original_output,
            perturbed_output
        ).ratio(),
        4
    )


# ============================================================
# INSTABILITY CLASSIFICATION
# ============================================================

def classify_instability(
    output_ratio,
    semantic_similarity,
):
    """
    Stable:
        Output nearly identical and semantic similarity high.

    Structural:
        Semantic similarity high but wording changed.

    Semantic:
        Semantic similarity dropped.
    """

    if semantic_similarity >= SEMANTIC_THRESHOLD:

        if output_ratio >= EDIT_RATIO_THRESHOLD:
            return "stable"

        return "structural"

    return "semantic"


# ============================================================
# HELPER
# ============================================================

def safe_similarity(value):
    """
    Handle NULL values from stability_scores.
    """

    if value is None:
        return 0.0

    return float(value)


