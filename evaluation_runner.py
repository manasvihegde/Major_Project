# ============================================================

def print_result(
    run_id,
    question_id,
    perturbation_type,
    output_ratio,
    semantic_similarity,
    category,
):

    print(
        f"[Run {run_id}] "
        f"Q{question_id:<3} | "
        f"{perturbation_type:<11} | "
        f"Edit={output_ratio:.4f} | "
        f"Semantic={semantic_similarity:.4f} | "
        f"{category.upper()}"
    )
    
    # ============================================================
# ANALYSIS
# ============================================================

def analyze_run(conn, run_id):
    """
    Analyze one completed run and categorize
    every perturbation.
    """

    questions = fetch_questions(conn, run_id)

    print(f"\nAnalyzing Run {run_id}")
    print(f"Questions Found : {len(questions)}")

    total = 0
    stable = 0
    structural = 0
    semantic = 0

    for question_id in questions:

        original_output = fetch_original_output(
            conn,
            run_id,
            question_id
        )

        if original_output is None:
            continue

        perturbations = fetch_perturbed_outputs(
            conn,
            run_id,
            question_id
        )

        for (
            perturbation_id,
            perturbation_type,
            perturbed_output
        ) in perturbations:

            semantic_similarity = fetch_semantic_similarity(
                conn,
                run_id,
                question_id,
                perturbation_type
            )

            if semantic_similarity is None:
                print(
                    f"Skipping Question {question_id}"
                    f" ({perturbation_type})"
                )
                continue

            output_ratio = output_edit_ratio(
                original_output,
                perturbed_output
            )

            category = classify_instability(
                output_ratio,
                semantic_similarity
            )

            insert_instability(
                conn,
                run_id,
                question_id,
                perturbation_id,
                perturbation_type,
                output_ratio,
                semantic_similarity,
                category
            )

            write_csv(
                run_id,
                question_id,
                perturbation_id,
                perturbation_type,
                output_ratio,
                semantic_similarity,
                category
            )

            print_result(
                run_id,
                question_id,
                perturbation_type,
                output_ratio,
                semantic_similarity,
                category
            )

            total += 1

            if category == "stable":
                stable += 1

            elif category == "structural":
                structural += 1

            else:
                semantic += 1

    print("\n==========================================")
    print(f"Run {run_id} Summary")
    print("==========================================")
    print(f"Total Comparisons : {total}")
    print(f"Stable            : {stable}")
    print(f"Structural        : {structural}")
    print(f"Semantic          : {semantic}")
    print("==========================================\n")


# ============================================================
# MAIN
# ============================================================

def main():

    print("\n==========================================")
    print("Week 2 - Instability Categorization")
    print("==========================================")

    initialize_csv()

    conn = get_connection()

    try:

        runs = fetch_all_runs(conn)

        if not runs:

            print("No completed runs found.")
            return

        print(f"\nCompleted Runs : {len(runs)}")

        for run_id in runs:

            analyze_run(
                conn,
                run_id
            )

        print("\n==========================================")
        print("Analysis Completed Successfully")
        print("==========================================")
        print(f"CSV Exported : {CSV_FILENAME}")

    except Exception as e:

        print("\nAnalysis Failed")
        print(e)

    finally:

        conn.close()


# ============================================================
# ENTRY POINT
# ============================================================

if __name__ == "__main__":
    main()